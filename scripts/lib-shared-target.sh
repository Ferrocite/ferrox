#!/usr/bin/env bash
# The one target dir every worktree builds into, and the only way to write or
# repair a worktree's pointer at it. Sourced, not run.
#
# Dependencies compile once and the relative `target/` paths in watch-test.sh,
# run-interop-baseline.sh, run-parity.sh and run-upstream-suite.sh all land on
# the same binaries, so both the config key and the symlink have to point here.
# A slice that wants a private build dir (a bisect, a rebuild race) passes
# CARGO_TARGET_DIR at the cargo call, which overrides this per invocation and
# leaves no pointer behind.

ferrox_shared_target() {
  local toplevel parent
  toplevel="$(git rev-parse --show-toplevel)"
  parent="$(cd "$toplevel/.." && pwd)"
  printf '%s\n' "$parent/.ferrox-target"
}

# Probe before pointing anything at it: a root-owned shared dir (one sudo'd build
# is enough) fails every cargo call, and the private dir that follows looks like
# a choice rather than a write failure.
ferrox_require_shared_writable() {
  local shared="$1" probe
  probe="$shared/.write-probe"
  mkdir -p "$shared" || {
    echo "::error::cannot create $shared" >&2
    return 1
  }
  if ! : >"$probe" 2>/dev/null; then
    rm -f "$probe" 2>/dev/null
    echo "::error::$shared is not writable by $(id -un): sudo chown -R $(id -un) $(id -gn) $shared" >&2
    return 1
  fi
  rm -f "$probe"
}

ferrox_write_cargo_config() {
  local dest="$1" shared="$2"
  mkdir -p "$dest/.cargo" "$shared"
  {
    echo "# Generated by scripts/new-worktree.sh / scripts/link-shared-target.sh. Never committed:"
    echo "# every worktree builds here so dependencies compile once."
    echo ""
    echo "[build]"
    echo "target-dir = \"$shared\""
    echo ""
    echo "# Hardware crypto for aarch64 builds, matching ci.yml so a local"
    echo "# measurement is of the code CI ships: the aes and polyval crates"
    echo "# (behind aes-gcm, i.e. every VMess header seal, AES data frame,"
    echo "# auth-id block and Shadowsocks chunk) compile their ARMv8-Crypto"
    echo "# backends only behind these cfgs and then runtime-dispatch, so a"
    echo "# device without the extension runs the soft code it runs today."
    echo "# Measured 12x on a VMess header seal and on a Cipher::Aes data frame."
    echo "# x86_64 consults neither cfg."
    echo "[target.aarch64-apple-darwin]"
    echo "rustflags = [\"--cfg\", \"aes_armv8\", \"--cfg\", \"polyval_armv8\"]"
    echo ""
    echo "[target.aarch64-unknown-linux-gnu]"
    echo "rustflags = [\"--cfg\", \"aes_armv8\", \"--cfg\", \"polyval_armv8\"]"
  } > "$dest/.cargo/config.toml"
}

# Replaces the pointer, never nests inside a real directory: `ln -sf src dir`
# would create `dir/target` and leave the per-worktree dir alive. A real
# directory that still holds artifacts moves into the shared dir's `aside/`, out
# of the worktree so `git status` stays clean and the bytes are kept.
ferrox_link_target() {
  local dest="$1" shared="$2" path="$1/target"
  if [[ -L "$path" ]]; then
    rm "$path"
  elif [[ -d "$path" ]]; then
    local aside
    aside="$shared/aside/$(basename "$dest").$(date +%s)"
    mkdir -p "$shared/aside"
    mv "$path" "$aside"
    echo "moved a real $path aside to $aside"
  elif [[ -e "$path" ]]; then
    rm "$path"
  fi
  ln -s "$shared" "$path"
}
